import '../models/word.dart';

Word _w(
  String word,
  String pos,
  String definition,
  List<String> insteadOf,
  String example,
  String cloze,
  String clozeAnswer,
  String forms, {
  Difficulty? difficulty,
}) => Word(
  word: word,
  partOfSpeech: pos,
  definition: definition,
  insteadOf: insteadOf,
  example: example,
  cloze: cloze,
  clozeAnswer: clozeAnswer,
  forms: forms.split(' '),
  difficulty:
      difficulty ??
      (_everyday.contains(word) ? Difficulty.everyday : Difficulty.stretch),
);

Word _advanced(
